"""Phase 17 Agent 5: the two evaluation lanes.

Specification sources: common contract section 11, Agent 1's frozen lane
semantics, Agent 5 instruction section 3.

```text
move_only          both setups fixed from the pack; EMA move weights only.
                   Records the paired setup digest and marks setup_used false.
joint_move_setup   opponent setup fixed; the PLAYER setup is generated by the
                   candidate's EMA setup network under the pack's frozen seeds.
```

The candidate plays on the accepted decision path
--------------------------------------------------
`Phase17CandidateSeat.decide` is `DirectSeat.decide` with a different owner
behind it: the same `build_policy_input`, the same `decide_checked`, the same
greedy tie-break. `play_board` -- the accepted Phase 15 game loop, unchanged --
runs the game. Nothing about the rules, the legality cross-check or the scoring
is reimplemented here, so a Phase 17 number is comparable to a Phase 16 one.

Setup generation happens once, in the parent, in pack order
------------------------------------------------------------
Batched matrix multiplication is not float-identical to the unbatched kind, so
"which batch was this setup drawn in" is part of the lane's definition rather
than an implementation detail. The lane therefore generates **all** cases of
one colour in a single call, in pack order, in the parent process -- on both
machines. A worker never touches the setup network. Changing this batching
would change generated setups and so would require a new pack version.

Failure is fatal, never repaired
--------------------------------
A generated setup that fails the accepted orientation gate, or whose seeds do
not match the ones the pack froze, aborts the lane. There is no fallback
library and no repair: contract section 13 makes a silent setup fallback a stop
condition, and a lane that quietly substituted a legal board would report a
number for a model that never produced it.
"""

