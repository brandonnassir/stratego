_COLOR_INDEX = {"red": 0, "blue": 1}


@dataclass(frozen=True)
class _CandidatePairing:
    """The `pairing` face `play_board` reads off a seat."""

    pairing_id: str
    move_model: str
    provider: str
    kind: str = "direct"

    def describe(self) -> dict:
        return {
            "pairing_id": self.pairing_id,
            "move_model": self.move_model,
            "provider": self.provider,
            "kind": self.kind,
        }


class Phase17CandidateSeat:
    """The candidate's move seat: EMA move weights, greedy, one forward."""

    kind = "direct"

    def __init__(self, owner, candidate_id: str) -> None:
        from ...evaluation.neural_worker import (
            DECISION_MODE_GREEDY,
            LocalInferenceChannel,
            RemoteNeuralPolicy,
        )
        from ...search.phase15.matchplay import player_ref

        self.pairing = _CandidatePairing(
            pairing_id=candidate_id,
            move_model=candidate_id,
            provider="phase17_move_ema",
        )
        self.arm_id = candidate_id
        self.ref = player_ref()
        self.policy = RemoteNeuralPolicy(
            self.ref,
            LocalInferenceChannel(owner),
            decision_mode=DECISION_MODE_GREEDY,
        )
        self.fallbacks: dict = {}

    def decide(self, state, legal, spec, plan):
        from ...evaluation.policy import build_policy_input

        request = build_policy_input(
            state,
            policy=self.ref,
            policy_seed=spec.policy_seed_for(state.acting_player),
            requirements=self.policy.requirements,
            suite_version=spec.suite_version,
            match_id=spec.match_id,
            paired_unit_id=spec.paired_unit_id,
            legal=legal,
        )
        started = time.perf_counter()
        result = self.policy.decide_checked(request)
        seconds = time.perf_counter() - started
        return int(result.selected_action_id), {
            "ply": int(state.total_moves),
            "seconds": seconds,
            "legal_actions": len(legal),
            "move_changed": None,
            "c1_forwards": 1,
            "unique_worlds": None,
            "candidates": None,
            "fallback": None,
            "direct_action_id": int(result.selected_action_id),
        }


