def _stratify(rows: "list[dict]", key: str) -> dict:
    strata: dict = {}
    for row in rows:
        bucket = strata.setdefault(
            str(row[key]), {"games": 0, "win": 0, "draw": 0, "loss": 0, "score": 0.0}
        )
        bucket["games"] += 1
        bucket["score"] += float(row["effective_score"])
        if row["effective_score"] >= 1.0:
            bucket["win"] += 1
        elif row["effective_score"] <= 0.0:
            bucket["loss"] += 1
        else:
            bucket["draw"] += 1
    for bucket in strata.values():
        bucket["ewr"] = round(bucket["score"] / bucket["games"], 6)
        bucket.pop("score")
    return strata


def score_lane(rows: "list[dict]", *, lane: str, setup_used: bool) -> dict:
    """Effective win rate overall and per stratum, with the binomial SE."""
    if not rows:
        raise Phase17EvaluationError(f"lane {lane} produced no games")
    games = len(rows)
    total = sum(float(row["effective_score"]) for row in rows)
    ewr = total / games
    variance = sum((float(row["effective_score"]) - ewr) ** 2 for row in rows)
    se = (variance / (games * max(games - 1, 1))) ** 0.5
    return {
        "lane": lane,
        "games": games,
        "ewr": round(ewr, 6),
        "se": round(se, 6),
        "wins": sum(1 for row in rows if row["effective_score"] >= 1.0),
        "draws": sum(1 for row in rows if 0.0 < row["effective_score"] < 1.0),
        "losses": sum(1 for row in rows if row["effective_score"] <= 0.0),
        "draw_score": DRAW_SCORE,
        "setup_used": bool(setup_used),
        "strata": {
            "by_opponent": _stratify(rows, "opponent"),
            "by_setup_source": _stratify(rows, "setup_source"),
            "by_color": _stratify(rows, "player_color"),
        },
    }


def lane_row(record, *, lane: str, board_id: str) -> dict:
    """The one row a played case contributes, small enough to return home."""
    return {
        "lane": lane,
        "board_id": board_id,
        "opponent": record.opponent,
        "opponent_class": record.opponent_class,
        "setup_source": record.setup_source,
        "player_color": record.player_color,
        "ordinal": int(record.ordinal),
        "outcome": record.outcome,
        "effective_score": float(record.effective_score),
        "terminal_reason": record.terminal_reason,
        "plies": int(record.plies),
        "player_decisions": int(record.player_decisions),
    }


