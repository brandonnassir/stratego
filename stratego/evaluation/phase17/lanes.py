def generate_joint_setups(setup_model, pack: dict, *, setup_digest: str, iteration: int) -> dict:
    """One generated player setup per joint case, keyed by board id.

    Generated in exactly two calls -- one per colour, in pack order -- because
    the batch a chain was drawn in is part of the lane's definition.
    """
    from ...belief.phase15.orientation import assert_engine_orientation
    from ...training.phase17.setup_sampling import generate_setups

    cases = pack["lanes"][LANE_JOINT]["cases"]
    generated: dict = {}
    for color_name, color in (("red", 0), ("blue", 1)):
        rows = [row for row in cases if row["player_color"] == color_name]
        if not rows:
            continue
        sampled = generate_setups(
            setup_model,
            run_id=JOINT_LANE_ID,
            game_ids=[row["board_id"] for row in rows],
            color=color,
            model_state_digest=setup_digest,
            snapshot_iteration=int(iteration),
            device="cpu",
        )
        if len(sampled) != len(rows):
            raise Phase17EvaluationError(
                f"{color_name}: generated {len(sampled)} setups for {len(rows)} cases"
            )
        for row, draw in zip(rows, sampled):
            if int(draw.root_seed) != int(row["setup_root_seed"]):
                raise Phase17EvaluationError(
                    f"{row['board_id']}: generated under root seed "
                    f"{draw.root_seed}, the pack froze {row['setup_root_seed']}"
                )
            if [int(value) for value in draw.per_token_seeds] != [
                int(value) for value in row["per_token_seeds"]
            ]:
                raise Phase17EvaluationError(
                    f"{row['board_id']}: per-token seeds differ from the pack"
                )
            # Fatal, never repaired: the accepted gate on every generated board.
            assert_engine_orientation(
                tuple(draw.canonical_setup), tuple(draw.engine_setup), color
            )
            generated[row["board_id"]] = {
                "engine_setup": [int(value) for value in draw.engine_setup],
                "canonical_setup": [int(value) for value in draw.canonical_setup],
                "canonical_fingerprint": draw.canonical_fingerprint,
                "root_seed": int(draw.root_seed),
            }
    if len(generated) != len(cases):
        raise Phase17EvaluationError(
            f"generated {len(generated)} setups for {len(cases)} joint cases"
        )
    return generated


def joint_plan(row: dict, generated: dict):
    """The joint case's board: opponent side fixed, player side generated."""
    engine_setup = generated[row["board_id"]]["engine_setup"]
    opponent_setup = row["opponent_engine_setup"]
    if row["player_color"] == "red":
        return plan_from_row(row, red_setup=engine_setup, blue_setup=opponent_setup)
    return plan_from_row(row, red_setup=opponent_setup, blue_setup=engine_setup)


