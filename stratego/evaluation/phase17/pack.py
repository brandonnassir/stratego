"""Phase 17 Agent 5: the immutable composite benchmark pack.

Specification sources: common contract section 11, Agent 1's frozen
`phase17_composite_benchmark_v1` semantics, Agent 5 instruction section 5.

Two lanes over one board set
----------------------------
```text
move_only          120 boards, BOTH setups fixed, EMA move weights only
joint_move_setup   the same 120 cases; the OPPONENT setup stays fixed and the
                   PLAYER setup is generated by the candidate's EMA setup
                   network under a per-case seed frozen in this pack
```
The move-only lane is the accepted `phase16_benchmark_v1` unchanged. The joint
lane reuses its opponents, colours, match seeds and opponent setups so that the
*only* difference between the two lanes is where the player's board came from.

Portable by construction, provably so
-------------------------------------
The accepted Phase 16 runner rebuilds each board by redrawing it from the 8,000
board setup library through the Phase 15 draw machinery. That is correct and it
is also unshippable: it would put a library, a selector and a draw stack on the
evaluating machine purely to reproduce bytes the manifest already contains.

So the pack ships the bytes -- and `build_composite_pack` proves it is allowed
to, by running `materialize_benchmark(verify=True)` on the machine that owns
the library and recording the result. If one setup byte of one board disagreed
with the library, the pack would not build. What travels is therefore the same
120 boards, not a re-derivation of them.

The player's setup is the measurement, so it is the one thing not frozen
--------------------------------------------------------------------------
Everything else about a joint case is pinned: opponent identity, opponent
setup, colour, match seed, and the setup RNG seeds themselves -- which are
derived under the *lane* id and never under the run id, so case 7 draws from
the same random stream at hour 0 and hour 12. Between two candidates the only
thing that can move is the setup network's weights, which is exactly the
quantity the lane exists to read.
"""

from __future__ import annotations

import json
from pathlib import Path

from .contract import (
    COMPOSITE_PACK_ID,
    EVALUATOR_VERSION,
    JOINT_LANE_ID,
    LANE_JOINT,
    LANE_MOVE_ONLY,
    MOVE_ONLY_BASE,
    MOVE_ONLY_BASE_DIGEST,
    MOVE_ONLY_BASE_FILE,
    Phase17PackError,
    joint_setup_seeds,
    json_digest,
)

#: Where the materialized pack lives, relative to the repository root.
DEFAULT_PACK_PATH = Path("data/phase17/phase17_composite_benchmark_v1.json")

#: The plan fields a row must carry for a board to be rebuilt without the
#: accepted library. Ordered, because the row is digested.
PLAN_FIELDS = (
    "board_id",
    "opponent",
    "setup_source",
    "requested_family",
    "player_color",
    "ordinal",
    "cell_index",
    "match_seed",
    "player_family_key",
    "opponent_family_key",
    "player_base_setup_id",
    "opponent_base_setup_id",
    "player_setup_branch",
    "opponent_setup_branch",
)

_COLOR_INDEX = {"red": 0, "blue": 1}


def _row_identity(row: dict) -> dict:
    return {field: row[field] for field in PLAN_FIELDS}


# ---------------------------------------------------------------------------
# Build (source side only -- needs the accepted setup library)
# ---------------------------------------------------------------------------


def build_composite_pack(*, root: "Path | str" = ".") -> dict:
    """Materialize the pack, proving the shipped bytes equal library bytes.

    Runs only on a machine that has the accepted setup library. The remote
    evaluator loads the result and never calls this.
    """
    from ..phase16.benchmark import (
        load_benchmark_manifest,
        manifest_digest,
        materialize_benchmark,
    )
    from ...belief.phase15.orientation import (
        ORIENTATION_RULE,
        ORIENTATION_RULE_VERSION,
    )

    root = Path(root)
    base_path = root / MOVE_ONLY_BASE_FILE
    manifest = load_benchmark_manifest(base_path)
    observed = manifest_digest(manifest)
    if observed != MOVE_ONLY_BASE_DIGEST or manifest["manifest_digest"] != observed:
        raise Phase17PackError(
            f"{base_path} digests to {observed}; the contract names "
            f"{MOVE_ONLY_BASE_DIGEST} as the accepted move-only base"
        )

    # The proof that the bytes may travel instead of the library.
    plans = materialize_benchmark(manifest, verify=True)
    if len(plans) != int(manifest["board_count"]):
        raise Phase17PackError(
            f"materialized {len(plans)} boards, manifest declares "
            f"{manifest['board_count']}"
        )
    by_id = {plan.board_id: plan for plan in plans}

    move_rows = []
    joint_rows = []
    for row in manifest["boards"]:
        plan = by_id[row["board_id"]]
        if list(plan.red_setup) != list(row["red_setup"]) or list(
            plan.blue_setup
        ) != list(row["blue_setup"]):
            raise Phase17PackError(
                f"{row['board_id']}: redrawn setup differs from the manifest"
            )
        identity = _row_identity(row)
        move_rows.append(
            dict(
                identity,
                red_setup=[int(value) for value in row["red_setup"]],
                blue_setup=[int(value) for value in row["blue_setup"]],
            )
        )

        color = row["player_color"]
        opponent_color = "blue" if color == "red" else "red"
        joint_rows.append(
            dict(
                identity,
                opponent_color=opponent_color,
                opponent_engine_setup=[
                    int(value) for value in row[f"{opponent_color}_setup"]
                ],
                player_setup="generated by the candidate setup EMA; not fixed",
                **joint_setup_seeds(row["board_id"], _COLOR_INDEX[color]),
            )
        )

    payload = {
        "artifact": COMPOSITE_PACK_ID,
        "pack_id": COMPOSITE_PACK_ID,
        "work_package": "phase17",
        "evaluator_version": EVALUATOR_VERSION,
        "frozen": (
            "this pack never changes; a change to cases, rules, seeds, "
            "inference math or scoring is a new version, never a silent edit"
        ),
        "packaging_note": (
            "setup BYTES travel instead of the accepted 8,000-board library; "
            "materialize_benchmark(verify=True) proved on the source machine "
            "that the shipped bytes are byte-identical to the library redraw"
        ),
        "library_redraw_proof": {
            "function": (
                "stratego.evaluation.phase16.benchmark.materialize_benchmark"
            ),
            "verify": True,
            "boards_checked": len(plans),
            "result": "every stored red_setup and blue_setup byte matched",
        },
        "orientation_rule": ORIENTATION_RULE,
        "orientation_rule_version": ORIENTATION_RULE_VERSION,
        "orientation_gate_note": (
            "move-only boards were gated by the accepted Phase 16 pack build "
            "and are bound here by digest; every GENERATED joint setup is "
            "gated remotely on every use, and a failure is fatal"
        ),
        "scoring": "effective win rate, draw = 0.5, overall and per stratum",
        "decision_instrument": (
            "the FULL 120-case move_only lane and the FULL 120-case "
            "joint_move_setup lane; quick subsets are not a decision instrument"
        ),
        "lanes": {
            LANE_MOVE_ONLY: {
                "lane_id": MOVE_ONLY_BASE,
                "base_manifest_digest": MOVE_ONLY_BASE_DIGEST,
                "base_file": MOVE_ONLY_BASE_FILE,
                "case_count": len(move_rows),
                "consumes_move": True,
                "consumes_setup": False,
                "setup_used": False,
                "records_paired_setup_digest_anyway": True,
                "both_setups_fixed": True,
                "cases": move_rows,
            },
            LANE_JOINT: {
                "lane_id": JOINT_LANE_ID,
                "case_count": len(joint_rows),
                "consumes_move": True,
                "consumes_setup": True,
                "setup_used": True,
                "seed_domain": (
                    f"setup_root_seed({JOINT_LANE_ID}, board_id, color); derived "
                    "under the LANE id, never under the run id"
                ),
                "fixed": [
                    "opponent setups",
                    "opponent identities",
                    "colours",
                    "match seeds",
                    "per-case setup RNG seeds",
                ],
                "not_fixed": (
                    "the player's setup, which is exactly what this lane measures"
                ),
                "cases": joint_rows,
            },
        },
        "strata": {
            "by_opponent": 10,
            "by_setup_source": 3,
            "by_color": 2,
            "cases_per_opponent": 12,
        },
        "source_identity": {
            "base_manifest_file_sha256": None,
            "generated_from": str(base_path),
        },
    }
    from .contract import file_sha256

    payload["source_identity"]["base_manifest_file_sha256"] = file_sha256(base_path)
    payload["pack_digest"] = json_digest(
        {key: value for key, value in payload.items() if key != "pack_digest"}
    )
    return payload


def write_composite_pack(payload: dict, path: "Path | str" = DEFAULT_PACK_PATH) -> Path:
    """Write the pack atomically; a reader never sees a half-written pack."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    staging = target.with_suffix(target.suffix + ".partial")
    staging.write_text(json.dumps(payload, indent=1, sort_keys=True) + "\n")
    staging.replace(target)
    return target


# ---------------------------------------------------------------------------
# Load and verify (both machines)
# ---------------------------------------------------------------------------


def load_composite_pack(
    path: "Path | str" = DEFAULT_PACK_PATH, *, expected_digest: "str | None" = None
) -> dict:
    """Load the pack and refuse it unless it re-digests to its own claim."""
    target = Path(path)
    if not target.is_file():
        raise Phase17PackError(f"no composite pack at {target}")
    payload = json.loads(target.read_text())
    if payload.get("artifact") != COMPOSITE_PACK_ID:
        raise Phase17PackError(f"{target} is not a {COMPOSITE_PACK_ID} document")
    claimed = payload.get("pack_digest")
    observed = json_digest(
        {key: value for key, value in payload.items() if key != "pack_digest"}
    )
    if claimed != observed:
        raise Phase17PackError(
            f"{target}: pack re-digests to {observed}, the document claims {claimed}"
        )
    if expected_digest is not None and observed != expected_digest:
        raise Phase17PackError(
            f"{target}: pack digest {observed} != the expected {expected_digest}; "
            "refusing to evaluate against an unbound benchmark"
        )
    for lane in (LANE_MOVE_ONLY, LANE_JOINT):
        block = payload["lanes"][lane]
        if len(block["cases"]) != int(block["case_count"]):
            raise Phase17PackError(
                f"{target}: lane {lane} declares {block['case_count']} cases and "
                f"carries {len(block['cases'])}"
            )
    return payload


def pack_digest(payload: dict) -> str:
    return json_digest(
        {key: value for key, value in payload.items() if key != "pack_digest"}
    )


# ---------------------------------------------------------------------------
# Rebuilding a board without the library
# ---------------------------------------------------------------------------


def plan_from_row(row: dict, *, red_setup=None, blue_setup=None):
    """A `Phase15BoardPlan` from a pack row, with no library and no draw.

    `red_setup`/`blue_setup` override the stored bytes; the joint lane uses
    that to substitute the generated player setup while leaving the opponent's
    side, the colour, the match seed and the opponent identity untouched.
    """
    from ...search.phase15.boards import Phase15BoardPlan

    if red_setup is None:
        red_setup = row["red_setup"]
    if blue_setup is None:
        blue_setup = row["blue_setup"]
    return Phase15BoardPlan(
        board_id=row["board_id"],
        opponent=row["opponent"],
        setup_source=row["setup_source"],
        requested_family=row["requested_family"],
        color=row["player_color"],
        ordinal=int(row["ordinal"]),
        cell_index=int(row["cell_index"]),
        match_seed=int(row["match_seed"]),
        red_setup=tuple(int(value) for value in red_setup),
        blue_setup=tuple(int(value) for value in blue_setup),
        player_family_key=row["player_family_key"],
        opponent_family_key=row["opponent_family_key"],
        player_base_setup_id=row["player_base_setup_id"],
        opponent_base_setup_id=row["opponent_base_setup_id"],
        player_setup_branch=row["player_setup_branch"],
        opponent_setup_branch=row["opponent_setup_branch"],
    )


