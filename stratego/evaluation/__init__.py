"""Phase 4 evaluation foundations: policy contract, match identity, setup bank.

Built on the frozen `phase2_1_reference_1.1.0` engine, which remains the sole
authority on legality, combat, terminal precedence and hidden information. This
package adds no rules and reads no privileged state:

- :mod:`policy` -- the observer-safe policy input/result contract every Phase 4
  baseline, future checkpoint and later search policy implements;
- :mod:`match_spec` -- deterministic match identity and paired colour-swap
  scheduling, independent of worker count and execution order;
- :mod:`setup_bank` -- the fixed, versioned, evaluation-only setup bank;
- :mod:`heuristics` -- observer-safe feature extraction and scoring primitives;
- :mod:`baselines` -- the four-tier baseline ladder;
- :mod:`stress` -- six unusual opponents that widen the game distribution;
- :mod:`registry` -- the named catalogue Agents 3 and 4 schedule from;
- :mod:`match_runner` -- deterministic game execution and reproducible parallel
  evaluation, plus the raw match-result schema;
- :mod:`scheduler` -- named, storable, digest-verified evaluation schedules;
- :mod:`statistics` -- effective win rate, paired-unit bootstrap intervals,
  colour/setup/terminal diagnostics and secondary league ratings;
- :mod:`reporting` -- raw CSV/JSON artefacts, replay sidecars and Markdown tables;
- :mod:`calibration` -- the parallel hidden-information audit, behavioural
  profiling by replay, and strength-tier partitioning from paired intervals.

Playing strength lives only in `baselines` and `stress`; the `contract_*` fixtures
in :mod:`policy` are interface tests and are deliberately absent from the
catalogue, and `calibration` is analysis rather than a policy.
"""

