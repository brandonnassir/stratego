"""The independent 4,096-pair random-opponent confirmation bank for Gate G1.

The G1 revision re-measures one contrast - the reproduction against the accepted
Phase 8 checkpoint, both playing the frozen random opponent - on setups that the
original comparison never used. Everything here exists to make "never used"
checkable rather than assumed.

**A new seed namespace, not a new seed convention.** The root seeds are derived
from the string `phase18_g1_random_confirmation_v1` through
`stratego.setups.identity.derive_stream_seed`, the project's recorded
domain-separated stream function, which exists precisely so no agent invents its
own mixing. Pairs are then generated by the accepted
`SetupBank.generate`/`derive_pair_seed` path, unchanged.

**Reflection classes, not just arrangements.** The Phase 18 evaluation contract
makes reflection-class de-duplication load-bearing: a setup and its horizontal
mirror are one class, and separation must be checked on the class fingerprint,
never on the canonical fingerprint alone. A pair is treated as ordered - red's
board and blue's board sit in different orientations, so `(A, B)` and `(B, A)`
are different positions - and its class identity is the pair of per-side class
fingerprints. That is deliberately stricter than "this whole board is the mirror
of that one": it also catches a pair that reuses one old side and freshens the
other.

Nothing in this module reads a game outcome. The bank is built and audited before
either checkpoint runs, and the audit's verdict is frozen into the contract.
"""

from __future__ import annotations

import hashlib
from dataclasses import asdict, dataclass

from stratego.engine.constants import BLUE, RED
from stratego.evaluation.setup_bank import (
    SetupBank,
    SetupPair,
    derive_pair_seed,
    serialize_setup,
    validate_bank,
)
from stratego.setups.identity import (
    class_fingerprint,
    content_fingerprint,
    deorient_setup,
    derive_stream_seed,
    reflect_canonical,
)

#: The versioned namespace every seed in this measurement descends from.
CONFIRMATION_NAMESPACE = "phase18_g1_random_confirmation_v1"

#: The bank's own version. `MatchSpec.resolve_setups` refuses a bank whose
#: version differs from the schedule's, so this string is what binds the frozen
#: schedule to these exact 4,096 boards.
CONFIRMATION_BANK_VERSION = "phase18_g1_random_confirmation_bank_v1"

#: Frozen by the Agent 3 instruction; 90% power at true delta 0 needs 3,769.
CONFIRMATION_PAIRS = 4096

#: Domain separation for the two pair-level fingerprints below.
PAIR_CONTENT_DOMAIN = "phase18_confirmation_pair_content_v1"
PAIR_CLASS_DOMAIN = "phase18_confirmation_pair_class_v1"


class ConfirmationBankError(ValueError):
    """A bank identity or separation failure. Always raised, never repaired."""


# ---------------------------------------------------------------------------
# Seeds
# ---------------------------------------------------------------------------


def namespace_seed(*parts: "int | str") -> int:
    """A seed in this measurement's namespace, through the recorded function."""
    return derive_stream_seed(CONFIRMATION_NAMESPACE, *parts)


def bank_root_seed() -> int:
    """Root seed of the confirmation setup bank."""
    return namespace_seed("setup_bank_root")


def schedule_root_seed() -> int:
    """Root seed of the paired match schedule."""
    return namespace_seed("schedule_root")


def bootstrap_seed() -> int:
    """Seed of the 10,000-replicate paired bootstrap."""
    return namespace_seed("paired_bootstrap")


# ---------------------------------------------------------------------------
# Fingerprints
# ---------------------------------------------------------------------------


def pair_canonical_setups(pair: SetupPair) -> tuple[tuple[int, ...], tuple[int, ...]]:
    """`(red, blue)` back in the canonical frame the fingerprints are defined on."""
    return (
        deorient_setup(pair.red_setup, RED),
        deorient_setup(pair.blue_setup, BLUE),
    )


def _combine(domain: str, left: str, right: str) -> str:
    return hashlib.sha256(f"{domain}:{left}:{right}".encode()).hexdigest()


def pair_content_fingerprint(pair: SetupPair) -> str:
    """Identity of one specific `(red, blue)` orientation."""
    red, blue = pair_canonical_setups(pair)
    return _combine(PAIR_CONTENT_DOMAIN, content_fingerprint(red), content_fingerprint(blue))


def pair_class_fingerprint(pair: SetupPair) -> str:
    """Identity of the pair's reflection class, per side.

    Equal for two pairs whenever each side lies in the same reflection class, so
    a mirrored board, a mirrored half, and an exact repeat all collide here.
    """
    red, blue = pair_canonical_setups(pair)
    return _combine(PAIR_CLASS_DOMAIN, class_fingerprint(red), class_fingerprint(blue))


def side_class_fingerprints(pair: SetupPair) -> tuple[str, str]:
    red, blue = pair_canonical_setups(pair)
    return class_fingerprint(red), class_fingerprint(blue)


def reflection_is_stable(pair: SetupPair) -> bool:
    """A pair's class fingerprints survive reflecting either side.

    Not a property of the bank so much as of the fingerprint: if this ever fails,
    the separation audit below is meaningless.
    """
    red, blue = pair_canonical_setups(pair)
    return (
        class_fingerprint(red) == class_fingerprint(reflect_canonical(red))
        and class_fingerprint(blue) == class_fingerprint(reflect_canonical(blue))
    )


# ---------------------------------------------------------------------------
# Construction
# ---------------------------------------------------------------------------


def build_confirmation_bank(size: int = CONFIRMATION_PAIRS) -> SetupBank:
    """Generate the confirmation bank from its namespace alone.

    Pure in the identity inputs: the same namespace and size always rebuild the
    same 4,096 boards, on any machine, without generating anything else first.
    """
    if size <= 0:
        raise ConfirmationBankError(f"bank size must be positive, got {size}")
    return SetupBank.generate(
        size=size,
        root_seed=bank_root_seed(),
        bank_version=CONFIRMATION_BANK_VERSION,
    )


# ---------------------------------------------------------------------------
# Separation audit
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class SeparationAudit:
    """Whether the confirmation bank is independent of the original bank."""

    confirmation_pairs: int
    reference_pairs: int
    reference_bank_version: str
    internal_content_duplicates: int
    internal_class_duplicates: int
    cross_content_overlap: int
    cross_class_overlap: int
    cross_side_class_overlap: int
    duplicate_pair_ids: int
    reflection_fingerprint_stable: bool
    structural_problems: list
    separated: bool

    def to_dict(self) -> dict:
        return asdict(self)


def separation_audit(
    confirmation: SetupBank, reference: SetupBank, *, check_structure: bool = True
) -> SeparationAudit:
    """Every separation property the instruction requires, counted."""
    new_content = [pair_content_fingerprint(p) for p in confirmation.pairs]
    new_class = [pair_class_fingerprint(p) for p in confirmation.pairs]
    old_content = {pair_content_fingerprint(p) for p in reference.pairs}
    old_class = {pair_class_fingerprint(p) for p in reference.pairs}

    old_side_class = set()
    for pair in reference.pairs:
        old_side_class.update(side_class_fingerprints(pair))
    new_side_class = []
    for pair in confirmation.pairs:
        new_side_class.extend(side_class_fingerprints(pair))

    identifiers = [p.setup_pair_id for p in confirmation.pairs]
    structure: list = []
    if check_structure:
        report = validate_bank(confirmation)
        structure = list(report["validation_failures"])
        if report["duplicate_setup_pair_ids"]:
            structure.append(
                f"duplicate setup_pair_ids: {report['duplicate_setup_pair_ids']}"
            )
        if report["distinct_positions"] != len(confirmation.pairs):
            structure.append(
                f"{len(confirmation.pairs)} pairs collapse to "
                f"{report['distinct_positions']} distinct positions"
            )

    audit = SeparationAudit(
        confirmation_pairs=len(confirmation.pairs),
        reference_pairs=len(reference.pairs),
        reference_bank_version=reference.bank_version,
        internal_content_duplicates=len(new_content) - len(set(new_content)),
        internal_class_duplicates=len(new_class) - len(set(new_class)),
        cross_content_overlap=len(old_content.intersection(new_content)),
        cross_class_overlap=len(old_class.intersection(new_class)),
        cross_side_class_overlap=len(old_side_class.intersection(new_side_class)),
        duplicate_pair_ids=len(identifiers) - len(set(identifiers)),
        reflection_fingerprint_stable=all(
            reflection_is_stable(p) for p in confirmation.pairs[:64]
        ),
        structural_problems=list(structure),
        separated=False,
    )
    separated = (
        audit.internal_content_duplicates == 0
        and audit.internal_class_duplicates == 0
        and audit.cross_content_overlap == 0
        and audit.cross_class_overlap == 0
        and audit.duplicate_pair_ids == 0
        and audit.reflection_fingerprint_stable
        and not audit.structural_problems
    )
    return SeparationAudit(**(audit.to_dict() | {"separated": separated}))


def bank_record(bank: SetupBank) -> dict:
    """The frozen, machine-readable description of a confirmation bank."""
    return {
        "bank_version": bank.bank_version,
        "namespace": CONFIRMATION_NAMESPACE,
        "seed_function": "stratego.setups.identity.derive_stream_seed",
        "root_seed": bank.root_seed,
        "generation_family": bank.generation_family,
        "pair_count": len(bank.pairs),
        "pair_ids": [p.setup_pair_id for p in bank.pairs],
        "bank_digest": bank.digest(),
        "pairs": [
            {
                "setup_pair_id": p.setup_pair_id,
                "generation_seed": p.generation_seed,
                "derived_seed_recomputes": p.generation_seed
                == derive_pair_seed(bank.root_seed, p.setup_pair_id),
                "red_setup": serialize_setup(p.red_setup),
                "blue_setup": serialize_setup(p.blue_setup),
                "pair_content_fingerprint": pair_content_fingerprint(p),
                "pair_class_fingerprint": pair_class_fingerprint(p),
            }
            for p in bank.pairs
        ],
    }
